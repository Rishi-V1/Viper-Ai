"""Builds an exportable incident report (spec section 12 "Reports" /
section 19 deliverable 7): evidence, scoring rationale, MITRE mappings,
limitations, and analyst-review status. Markdown first, as the spec
recommends; HTML is a thin wrapper around it.
"""

import json
from datetime import datetime, timezone


def build_markdown(incident: dict) -> str:
    breakdown = incident["score_breakdown"]
    if isinstance(breakdown, str):
        breakdown = json.loads(breakdown)

    lines = [
        f"# Incident Report: {incident['title']}",
        "",
        f"- **Incident ID:** {incident['incident_id']}",
        f"- **Status:** {incident['status']}",
        f"- **Severity:** {incident['severity']} / 100 ({incident['severity_label']})",
        f"- **Confidence:** {incident['confidence']}",
        f"- **Rule fired:** {incident['rule_fired']}",
        f"- **First seen:** {incident['first_seen']}",
        f"- **Last seen:** {incident['last_seen']}",
        f"- **Report generated:** {datetime.now(timezone.utc).isoformat()}",
        "",
        "## Why these events were linked",
        "",
        incident["why_linked"],
        "",
        "## Risk score breakdown",
        "",
        "| Factor | Points |",
        "|---|---|",
    ]
    for factor, value in breakdown.items():
        if factor == "assets_considered":
            continue
        lines.append(f"| {factor} | {value} |")

    lines += ["", "## Evidence", "", "| Event ID | Timestamp | Type | Source/Dest | Host | Signature |", "|---|---|---|---|---|---|"]
    for e in incident.get("evidence", []):
        src_dst = f"{e.get('src_ip') or '-'} -> {e.get('dest_ip') or '-'}"
        lines.append(
            f"| {e['event_id']} | {e['timestamp']} | {e['event_type']} | {src_dst} | "
            f"{e.get('host_id') or '-'} | {e.get('signature') or '-'} |"
        )

    mappings = incident.get("attack_mappings", [])
    if mappings:
        lines += ["", "## MITRE ATT&CK references", ""]
        for m in mappings:
            lines.append(
                f"- **{m['technique_id']} — {m['technique_name']}** "
                f"({m['qualification']}): {m['rationale']} "
                f"(supporting events: {', '.join(m['supporting_event_ids'])})"
            )

    lines += [
        "",
        "## Limitations and uncertainty",
        "",
        "- This correlation is a hypothesis for investigation, not proof of compromise.",
        "- Alternative benign explanations have not been ruled out by this report alone.",
        "- Any AI-generated analysis attached to this incident requires analyst review before action.",
        "",
        "---",
        "*Lab / authorized-use only. Generated by BlueShield.*",
    ]
    return "\n".join(lines)


def build_html(incident: dict) -> str:
    markdown = build_markdown(incident)
    # Minimal, dependency-free Markdown->HTML: good enough for a report
    # export; a full renderer is unnecessary for this scope.
    escaped = markdown.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return f"<html><head><meta charset='utf-8'><title>{incident['title']}</title></head><body><pre>{escaped}</pre></body></html>"
